#!/usr/bin/env python3
# Embeds third_party/flags/png/*.png (country flags, 40 px high, from
# flagcdn.com - public domain) into src/gui/flags_data.h.
#
#   python3 tools/gen_flags.py

import os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = os.path.join(root, "third_party", "flags", "png")
dst = os.path.join(root, "src", "gui", "flags_data.h")

files = sorted(f for f in os.listdir(src) if f.endswith(".png"))
with open(dst, "w", newline="\n") as out:
    out.write("// Generated by tools/gen_flags.py - country flags (flagcdn.com, public domain)\n")
    out.write("#pragma once\n\n#include <cstddef>\n\n")
    out.write("struct FlagPng { const char *iso; const unsigned char *data; size_t size; };\n\n")
    for f in files:
        data = open(os.path.join(src, f), "rb").read()
        out.write("static const unsigned char flag_%s[] = {" % f[:-4])
        for i, b in enumerate(data):
            out.write(("\n    " if i % 20 == 0 else "") + "%d," % b)
        out.write("\n};\n")
    out.write("\nstatic const FlagPng kFlags[] = {\n")
    for f in files:
        out.write('    {"%s", flag_%s, sizeof(flag_%s)},\n' % (f[:-4], f[:-4], f[:-4]))
    out.write("};\n")
print("wrote", dst, len(files), "flags")
