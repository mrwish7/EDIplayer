#!/usr/bin/env python3
# Draws the EDIplayer icon: "EDI" in an accent-blue box on the app's dark
# tile, with "player" underneath (sizes <= 32 px show just the EDI box, as
# the small text would only be noise there).
#
#   python3 tools/gen_icon.py        (needs Pillow and the Segoe UI or DejaVu fonts)
#
# Writes res/icon.ico (Windows exe + window icon), res/icon_<size>.png, and
# src/gui/icon_data.h (PNGs embedded for glfwSetWindowIcon on Linux).

import io, os
from PIL import Image, ImageDraw, ImageFont

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
res = os.path.join(root, "res")
os.makedirs(res, exist_ok=True)

BG = (28, 31, 38, 255)          # app panel colour
EDGE = (255, 255, 255, 22)
ACCENT = (51, 140, 242, 255)    # kAccent (0.20, 0.55, 0.95)
WHITE = (255, 255, 255, 255)
SUB = (200, 205, 214, 255)

FONTS_BOLD = ["/mnt/c/Windows/Fonts/segoeuib.ttf", "C:/Windows/Fonts/segoeuib.ttf",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"]
FONTS_SEMI = ["/mnt/c/Windows/Fonts/seguisb.ttf", "C:/Windows/Fonts/seguisb.ttf",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]


def font_path(cands):
    for f in cands:
        if os.path.exists(f):
            return f
    raise SystemExit("no font found")


BOLD, SEMI = font_path(FONTS_BOLD), font_path(FONTS_SEMI)


def fit_font(path, text, max_w, max_h):
    """Largest font size whose ink box fits max_w x max_h"""
    size = 4
    while True:
        f = ImageFont.truetype(path, size + 1)
        l, t, r, b = f.getbbox(text)
        if r - l > max_w or b - t > max_h:
            return ImageFont.truetype(path, size)
        size += 1


def draw_centered(d, text, font, cx, cy, fill):
    l, t, r, b = font.getbbox(text)
    d.text((cx - (l + r) / 2, cy - (t + b) / 2), text, font=font, fill=fill)


def render(size):
    S = size * 4                      # supersample, then downscale
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    m = S * 0.03
    d.rounded_rectangle([m, m, S - m, S - m], radius=S * 0.2, fill=BG, outline=EDGE, width=max(1, int(S * 0.012)))

    small = size <= 32
    bw, bh = (0.80, 0.52) if small else (0.74, 0.40)
    top = 0.24 if small else 0.15
    x0, y0 = S * (1 - bw) / 2, S * top
    x1, y1 = x0 + S * bw, y0 + S * bh
    stroke = S * (0.075 if small else 0.045)
    d.rounded_rectangle([x0, y0, x1, y1], radius=S * 0.06, outline=ACCENT, width=int(stroke))
    edi = fit_font(BOLD, "EDI", (x1 - x0) - stroke * 3.2, (y1 - y0) - stroke * 3.2)
    draw_centered(d, "EDI", edi, (x0 + x1) / 2, (y0 + y1) / 2, WHITE)

    if not small:
        player = fit_font(SEMI, "player", S * 0.70, S * 0.17)
        draw_centered(d, "player", player, S / 2, S * 0.745, SUB)
    return img.resize((size, size), Image.LANCZOS)


sizes = [16, 24, 32, 48, 64, 128, 256]
imgs = {s: render(s) for s in sizes}
for s, im in imgs.items():
    im.save(os.path.join(res, "icon_%d.png" % s))
# Pillow writes each requested size from the largest image unless given them all
imgs[256].save(os.path.join(res, "icon.ico"), sizes=[(s, s) for s in sizes],
               append_images=[imgs[s] for s in sizes if s != 256])

# embedded PNGs for glfwSetWindowIcon (GLFW picks the best size)
with open(os.path.join(root, "src", "gui", "icon_data.h"), "w", newline="\n") as out:
    out.write("// Generated by tools/gen_icon.py - EDIplayer window icon\n#pragma once\n\n#include <cstddef>\n\n")
    out.write("struct IconPng { const unsigned char *data; size_t size; };\n\n")
    names = []
    for s in (16, 32, 48, 128):
        buf = io.BytesIO()
        imgs[s].save(buf, "PNG")
        data = buf.getvalue()
        out.write("static const unsigned char icon_png_%d[] = {" % s)
        for i, b in enumerate(data):
            out.write(("\n    " if i % 20 == 0 else "") + "%d," % b)
        out.write("\n};\n")
        names.append("icon_png_%d" % s)
    out.write("\nstatic const IconPng kIconPngs[] = {\n")
    for n in names:
        out.write("    {%s, sizeof(%s)},\n" % (n, n))
    out.write("};\n")
print("icon written:", ", ".join(str(s) for s in sizes))
